function files = generate_behavior_showcase_scenarios(varargin)
%GENERATE_BEHAVIOR_SHOWCASE_SCENARIOS 生成用于观察明显规避行为的示例场景。
% 该脚本会分别生成突发、动态和融合场景，并保存对应 GIF。参数比默认批量
% 数据集更“戏剧化”，用于人工检查无人机是否因特殊威胁改变突防策略。
%
% 示例：
%   addpath('data_create');
%   files = generate_behavior_showcase_scenarios("seed", 20260605);

    parser = inputParser;
    parser.addParameter("outputRoot", fullfile("data", "unverified_dataset", "behavior_showcase"), @(x)ischar(x) || isstring(x));
    parser.addParameter("seed", 20260605, @(x)isempty(x) || isnumeric(x));
    parser.addParameter("maxAttempts", 25, @(x)isnumeric(x) && isscalar(x) && x >= 1);
    parser.addParameter("frameStep", 4, @(x)isnumeric(x) && isscalar(x) && x >= 1);
    parser.addParameter("showFigure", false, @(x)islogical(x) || isnumeric(x));
    parser.parse(varargin{:});
    opt = parser.Results;

    addpath(fileparts(mfilename("fullpath")));
    files = strings(0, 1);

    configs = [
        showcase_config("sudden", 70001, opt.seed, "突发威胁规避示例")
        showcase_config("dynamic", 71001, opt.seed + 100, "动态威胁拦截示例")
        showcase_config("fusion", 72001, opt.seed + 200, "融合威胁规避示例")
    ];

    for i = 1:numel(configs)
        cfg = configs(i);
        fprintf("Generating %s...\n", cfg.description);
        generated = generate_penetration_dataset(cfg.scenarioType, ...
            "numSamples", 1, ...
            "startIndex", cfg.startIndex, ...
            "outputRoot", opt.outputRoot, ...
            "seed", cfg.seed, ...
            "maxAttempts", opt.maxAttempts, ...
            "saveFailed", false, ...
            cfg.params{:});
        files = [files; generated(:)]; %#ok<AGROW>
        for j = 1:numel(generated)
            plot_penetration_scene(generated(j), ...
                "showFigure", logical(opt.showFigure), ...
                "saveOutput", true, ...
                "makeGif", true, ...
                "frameStep", opt.frameStep);
        end
    end
end

function cfg = showcase_config(scenarioType, startIndex, seed, description)
    common = { ...
        "baseThreatMode", "random", ...
        "radarIntrusionWeight", 18, ...
        "weaponProximityWeight", 7, ...
        "weaponProximityBuffer", 0.5, ...
        "terminalTolerance", 50};

    switch string(scenarioType)
        case "sudden"
            params = [common, { ...
                "numCircles", 5, ...
                "numSuddenThreats", 2, ...
                "suddenThreatClassMode", "mixed", ...
                "suddenTriggerDistanceRange", [6200, 8200]}];
        case "dynamic"
            params = [common, { ...
                "numCircles", 5, ...
                "numDynamicThreats", 2, ...
                "dynamicThreatClassMode", "mixed", ...
                "dynamicMoveStartRange", [45, 45], ...
                "dynamicMoveDurationRange", [80, 120], ...
                "dynamicResponseDistanceRange", [10000, 10000], ...
                "dynamicThreatSpeedRange", [220, 300]}];
        case "fusion"
            params = [common, { ...
                "numCircles", 6, ...
                "numSuddenThreats", 2, ...
                "numDynamicThreats", 1, ...
                "suddenThreatClassMode", "random", ...
                "dynamicThreatClassMode", "random", ...
                "suddenTriggerDistanceRange", [6000, 8000], ...
                "targetSpeedRange", [8, 16], ...
                "targetHeadingRange", deg2rad([-20, 20]), ...
                "dynamicMoveStartRange", [45, 45], ...
                "dynamicMoveDurationRange", [75, 115], ...
                "dynamicResponseDistanceRange", [10000, 10000], ...
                "dynamicThreatSpeedRange", [220, 300]}];
        otherwise
            error("未知展示场景类型: %s", scenarioType);
    end

    cfg = struct("scenarioType", string(scenarioType), ...
        "startIndex", startIndex, ...
        "seed", seed, ...
        "description", string(description), ...
        "params", {params});
end
